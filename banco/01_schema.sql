-- =====================================================================
-- 5. VIEW DE APOIO A LISTAGEM (junta os nomes de tipo, prioridade, status,
--    projeto e responsavel; usada pela API na listagem e no dashboard)
-- =====================================================================
CREATE OR REPLACE VIEW VW_DEMANDA_LISTAGEM AS
SELECT d.ID_DEMANDA,
       d.TITULO,
       d.DESCRICAO,
       t.NOME           AS TIPO,
       pr.NOME          AS PRIORIDADE,
       pr.NIVEL         AS NIVEL_PRIORIDADE,
       s.NOME           AS STATUS,
       s.ORDEM          AS ORDEM_STATUS,
       s.STATUS_FINAL,
       p.ID_PROJETO,
       p.NOME           AS PROJETO,
       d.ID_RESPONSAVEL,
       r.NOME           AS RESPONSAVEL,
       d.ID_CRIADOR,
       d.DATA_CRIACAO,
       d.DATA_ATUALIZACAO,
       d.PRAZO_FINALIZACAO
  FROM DEMANDA d
  JOIN TIPO_DEMANDA   t  ON t.ID_TIPO        = d.ID_TIPO
  JOIN PRIORIDADE     pr ON pr.ID_PRIORIDADE = d.ID_PRIORIDADE
  JOIN STATUS_DEMANDA s  ON s.ID_STATUS      = d.ID_STATUS
  JOIN PROJETO        p  ON p.ID_PROJETO     = d.ID_PROJETO
  LEFT JOIN USUARIO   r  ON r.ID_USUARIO     = d.ID_RESPONSAVEL;