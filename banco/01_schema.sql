-- =====================================================================
-- 0. LIMPEZA - permite executar o script quantas vezes for necessario
-- =====================================================================
-- Apaga as tabelas que ja existirem; CASCADE CONSTRAINTS remove junto as
-- chaves estrangeiras, entao a ordem da lista nao importa.
BEGIN
  FOR t IN (SELECT table_name
              FROM user_tables
             WHERE table_name IN ('HISTORICO_ALTERACAO', 'COMENTARIO', 'DEMANDA',
                                  'PROJETO_USUARIO', 'USUARIO', 'PROJETO',
                                  'STATUS_DEMANDA', 'PRIORIDADE', 'TIPO_DEMANDA',
                                  'PERFIL'))
  LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/


-- =====================================================================
-- 1. TABELAS DE DOMINIO (valores fixos definidos no documento de escopo)
-- =====================================================================

-- Perfis de acesso: Administrador, Lider de Projeto, Membro da Equipe
CREATE TABLE PERFIL (
  ID_PERFIL   NUMBER(2)      NOT NULL,
  NOME        VARCHAR2(30)   NOT NULL,
  DESCRICAO   VARCHAR2(200),
  CONSTRAINT PK_PERFIL      PRIMARY KEY (ID_PERFIL),
  CONSTRAINT UK_PERFIL_NOME UNIQUE (NOME)
);

-- Tipos de demanda: Tarefa, Defeito, Melhoria, Documentacao
CREATE TABLE TIPO_DEMANDA (
  ID_TIPO     NUMBER(2)      NOT NULL,
  NOME        VARCHAR2(30)   NOT NULL,
  CONSTRAINT PK_TIPO_DEMANDA      PRIMARY KEY (ID_TIPO),
  CONSTRAINT UK_TIPO_DEMANDA_NOME UNIQUE (NOME)
);

-- Prioridades: NIVEL serve para ordenar (1 = Critica, a mais urgente)
CREATE TABLE PRIORIDADE (
  ID_PRIORIDADE NUMBER(2)    NOT NULL,
  NOME          VARCHAR2(20) NOT NULL,
  NIVEL         NUMBER(1)    NOT NULL,
  CONSTRAINT PK_PRIORIDADE       PRIMARY KEY (ID_PRIORIDADE),
  CONSTRAINT UK_PRIORIDADE_NOME  UNIQUE (NOME),
  CONSTRAINT UK_PRIORIDADE_NIVEL UNIQUE (NIVEL)
);

-- Status: ORDEM segue o fluxo; STATUS_FINAL = 'S' para Concluida/Cancelada
CREATE TABLE STATUS_DEMANDA (
  ID_STATUS    NUMBER(2)    NOT NULL,
  NOME         VARCHAR2(20) NOT NULL,
  ORDEM        NUMBER(2)    NOT NULL,
  STATUS_FINAL CHAR(1)      DEFAULT 'N' NOT NULL,
  CONSTRAINT PK_STATUS_DEMANDA      PRIMARY KEY (ID_STATUS),
  CONSTRAINT UK_STATUS_DEMANDA_NOME UNIQUE (NOME),
  CONSTRAINT CK_STATUS_FINAL        CHECK (STATUS_FINAL IN ('S', 'N'))
);


-- =====================================================================
-- 2. TABELAS PRINCIPAIS
-- =====================================================================

CREATE TABLE USUARIO (
  ID_USUARIO   NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  NOME         VARCHAR2(100) NOT NULL,
  EMAIL        VARCHAR2(150) NOT NULL,
  SENHA_HASH   VARCHAR2(255) NOT NULL,          -- senha criptografada (bcrypt) pela API
  ID_PERFIL    NUMBER(2)     NOT NULL,
  ATIVO        CHAR(1)       DEFAULT 'S' NOT NULL,
  DATA_CRIACAO TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_USUARIO        PRIMARY KEY (ID_USUARIO),
  CONSTRAINT UK_USUARIO_EMAIL  UNIQUE (EMAIL),
  CONSTRAINT FK_USUARIO_PERFIL FOREIGN KEY (ID_PERFIL) REFERENCES PERFIL (ID_PERFIL),
  CONSTRAINT CK_USUARIO_ATIVO  CHECK (ATIVO IN ('S', 'N'))
);

CREATE TABLE PROJETO (
  ID_PROJETO   NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
  NOME         VARCHAR2(100)  NOT NULL,
  DESCRICAO    VARCHAR2(1000),
  DATA_INICIO  DATE           DEFAULT SYSDATE NOT NULL,
  ATIVO        CHAR(1)        DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_PROJETO       PRIMARY KEY (ID_PROJETO),
  CONSTRAINT UK_PROJETO_NOME  UNIQUE (NOME),
  CONSTRAINT CK_PROJETO_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

-- Tabela associativa do relacionamento N:N "participa" (USUARIO x PROJETO)
-- ATIVO permite desfazer o vinculo sem exclusao fisica
CREATE TABLE PROJETO_USUARIO (
  ID_PROJETO   NUMBER(10) NOT NULL,
  ID_USUARIO   NUMBER(10) NOT NULL,
  DATA_VINCULO DATE       DEFAULT SYSDATE NOT NULL,
  ATIVO        CHAR(1)    DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_PROJETO_USUARIO PRIMARY KEY (ID_PROJETO, ID_USUARIO),
  CONSTRAINT FK_PROJUSU_PROJETO FOREIGN KEY (ID_PROJETO) REFERENCES PROJETO (ID_PROJETO),
  CONSTRAINT FK_PROJUSU_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT CK_PROJUSU_ATIVO   CHECK (ATIVO IN ('S', 'N'))
);

-- Entidade central do sistema.
-- Status inicial "Aberta" e datas automaticas: a API define esses valores
-- no POST /demandas; os DEFAULT abaixo cobrem um INSERT feito direto no banco.
CREATE TABLE DEMANDA (
  ID_DEMANDA        NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
  TITULO            VARCHAR2(150)  NOT NULL,
  DESCRICAO         VARCHAR2(4000) NOT NULL,
  ID_TIPO           NUMBER(2)      NOT NULL,
  ID_PRIORIDADE     NUMBER(2)      NOT NULL,
  ID_STATUS         NUMBER(2)      DEFAULT 1 NOT NULL,   -- 1 = Aberta
  ID_PROJETO        NUMBER(10)     NOT NULL,
  ID_RESPONSAVEL    NUMBER(10),                          -- pode ficar em branco
  ID_CRIADOR        NUMBER(10)     NOT NULL,
  DATA_CRIACAO      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  DATA_ATUALIZACAO  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  PRAZO_FINALIZACAO DATE,                                -- validado contra feriados pela API
  CONSTRAINT PK_DEMANDA             PRIMARY KEY (ID_DEMANDA),
  CONSTRAINT FK_DEMANDA_TIPO        FOREIGN KEY (ID_TIPO)
             REFERENCES TIPO_DEMANDA (ID_TIPO),
  CONSTRAINT FK_DEMANDA_PRIORIDADE  FOREIGN KEY (ID_PRIORIDADE)
             REFERENCES PRIORIDADE (ID_PRIORIDADE),
  CONSTRAINT FK_DEMANDA_STATUS      FOREIGN KEY (ID_STATUS)
             REFERENCES STATUS_DEMANDA (ID_STATUS),
  CONSTRAINT FK_DEMANDA_PROJETO     FOREIGN KEY (ID_PROJETO)
             REFERENCES PROJETO (ID_PROJETO),
  CONSTRAINT FK_DEMANDA_RESPONSAVEL FOREIGN KEY (ID_RESPONSAVEL)
             REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT FK_DEMANDA_CRIADOR     FOREIGN KEY (ID_CRIADOR)
             REFERENCES USUARIO (ID_USUARIO),
  -- o prazo nao pode ser anterior ao dia em que a demanda foi criada
  CONSTRAINT CK_DEMANDA_PRAZO       CHECK (PRAZO_FINALIZACAO IS NULL
                                           OR PRAZO_FINALIZACAO >= TRUNC(DATA_CRIACAO))
);

-- Comentario: sempre vinculado a uma demanda e a um usuario, com data e hora
CREATE TABLE COMENTARIO (
  ID_COMENTARIO NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY,
  ID_DEMANDA    NUMBER(10)     NOT NULL,
  ID_USUARIO    NUMBER(10)     NOT NULL,
  TEXTO         VARCHAR2(2000) NOT NULL,
  DATA_HORA     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_COMENTARIO         PRIMARY KEY (ID_COMENTARIO),
  CONSTRAINT FK_COMENTARIO_DEMANDA FOREIGN KEY (ID_DEMANDA) REFERENCES DEMANDA (ID_DEMANDA),
  CONSTRAINT FK_COMENTARIO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)
);

-- Historico de alteracoes: a API so faz INSERT aqui (nunca UPDATE nem DELETE)
CREATE TABLE HISTORICO_ALTERACAO (
  ID_HISTORICO   NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
  ID_DEMANDA     NUMBER(10)    NOT NULL,
  ID_USUARIO     NUMBER(10)    NOT NULL,   -- quem fez a alteracao
  TIPO_ALTERACAO VARCHAR2(20)  NOT NULL,
  VALOR_ANTERIOR VARCHAR2(200),
  VALOR_NOVO     VARCHAR2(200),
  DESCRICAO      VARCHAR2(500) NOT NULL,   -- ex.: "Joao alterou o status de Aberta para Em andamento."
  DATA_HORA      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_HISTORICO_ALTERACAO PRIMARY KEY (ID_HISTORICO),
  CONSTRAINT FK_HISTORICO_DEMANDA   FOREIGN KEY (ID_DEMANDA) REFERENCES DEMANDA (ID_DEMANDA),
  CONSTRAINT FK_HISTORICO_USUARIO   FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
  CONSTRAINT CK_HISTORICO_TIPO      CHECK (TIPO_ALTERACAO IN ('CRIACAO', 'STATUS', 'RESPONSAVEL',
                                           'PRIORIDADE', 'PRAZO', 'EDICAO', 'CANCELAMENTO'))
);


-- =====================================================================
